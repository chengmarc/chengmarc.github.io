let LANG = 'en';

// The first of the browser's languages we have; every Chinese variant
// (zh-TW and zh-HK included) gets Simplified, the only Chinese offered.
function browserLanguage() {
	for (const tag of navigator.languages || [navigator.language || 'en']) {
		const l = String(tag).toLowerCase();
		if (l.startsWith('zh')) return 'zh-CN';
		const base = l.split('-')[0];
		if (STRINGS[base]) return base;
	}
	return 'en';
}

// The locale for dates and times: the browser's own regional tag when it is
// the same language (en-GB keeps its 24-hour clock), else the language.
function locale() {
	const base = LANG.split('-')[0];
	const own = (navigator.languages || []).find(tag => String(tag).toLowerCase().split('-')[0] === base);
	return own || LANG;
}

function t(key, vars) {
	let s = (STRINGS[LANG] && STRINGS[LANG][key]) ?? STRINGS.en[key] ?? key;
	if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
	return s;
}

// data-i18n* attribute → what it fills: null for the text itself.
const I18N_ATTRS = { 'data-i18n': null, 'data-i18n-title': 'title', 'data-i18n-placeholder': 'placeholder', 'data-i18n-aria': 'aria-label' };

function translatePage(root = document) {
	for (const [data, attr] of Object.entries(I18N_ATTRS)) {
		root.querySelectorAll('[' + data + ']').forEach(n => {
			const s = t(n.getAttribute(data));
			if (attr) n.setAttribute(attr, s); else n.textContent = s;
		});
	}
}

const languageHooks = [];
function onLanguageChange(fn) { languageHooks.push(fn); }

// The saved choice ('auto' or a code), else the browser's language.
function applyLanguage() {
	LANG = STRINGS[settings.language] ? settings.language : browserLanguage();
	document.documentElement.lang = LANG;
	translatePage();
	languageHooks.forEach(fn => fn());
}
